<?php

namespace Embiken\BikeFleet\Filament\Resources\Parts\Schemas;

use Filament\Forms\Components\TextInput;
use Filament\Schemas\Schema;

class PartForm
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                TextInput::make('name')
                    ->required()
                    ->maxLength(255)
                    ->unique(ignoreRecord: true),
                TextInput::make('sku')
                    ->label('SKU')
                    ->nullable()
                    ->maxLength(100),
            ]);
    }
}
